// Copies Gridword's answer list into the Worker (src/answers.js), so the server knows each day's word.
// Runs automatically before `wrangler dev` and `wrangler deploy` (see [build] in wrangler.toml).
import fs from 'node:fs';
import vm from 'node:vm';

const source = fs.readFileSync(new URL('../public/games/gridword/words.js', import.meta.url), 'utf8');
const sandbox = { window: {} };
vm.runInNewContext(source, sandbox);
const answers = sandbox.window.GRIDWORD_WORDS && sandbox.window.GRIDWORD_WORDS.answers;
if (!Array.isArray(answers) || answers.length < 100) throw new Error('Could not read the Gridword answers');
const out = new URL('./src/answers.js', import.meta.url);
const text = '// Generated by gen-answers.mjs from public/games/gridword/words.js. Do not edit.\nexport default ' + JSON.stringify(answers) + ';\n';
// Only write when it changed, so the dev server's file watcher doesn't rebuild in a loop.
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) {
  fs.writeFileSync(out, text);
  console.log('Gridword answers for the Worker:', answers.length);
}
